import { Router } from 'express';
import { AutomationController } from './automation.controller.js';
import {
  executeWorkflowSchema,
  previewWorkflowSchema,
  listExecutionsQuerySchema,
  evaluateDependenciesSchema
} from './automation.validation.js';
import { authenticate } from '../../middleware/authenticate.js';
import { requirePermission } from '../../middleware/authorize.js';
import { validate } from '../../middleware/validate.js';
import { csrfProtection } from '../../utils/csrf.js';

const router = Router();

router.use(authenticate);

// Preview workflow generation (read-only, does not create tasks)
router.post(
  '/automation/preview',
  requirePermission('workflows.view'),
  validate(previewWorkflowSchema),
  AutomationController.preview
);

// Initialize / execute workflow automation
router.post(
  '/automation/execute',
  requirePermission('workflows.execute'),
  csrfProtection,
  validate(executeWorkflowSchema),
  AutomationController.initialize
);

// List workflow executions
router.get(
  '/automation/executions',
  requirePermission('workflows.view'),
  validate(listExecutionsQuerySchema, 'query'),
  AutomationController.listExecutions
);

// Get execution status & details
router.get(
  '/automation/executions/:id',
  requirePermission('workflows.view'),
  AutomationController.getExecution
);

// Get tasks generated by an execution
router.get(
  '/automation/executions/:id/tasks',
  requirePermission('workflows.view'),
  AutomationController.getExecutionTasks
);

// Get execution errors
router.get(
  '/automation/executions/:id/errors',
  requirePermission('workflows.view'),
  AutomationController.getExecutionErrors
);

// Retry an eligible failed execution
router.post(
  '/automation/executions/:id/retry',
  requirePermission('workflows.execute'),
  csrfProtection,
  AutomationController.retryExecution
);

// Evaluate / refresh runtime task dependencies
router.post(
  '/automation/evaluate-dependencies',
  requirePermission('workflows.execute'),
  csrfProtection,
  validate(evaluateDependenciesSchema),
  AutomationController.evaluateDependencies
);

export default router;
